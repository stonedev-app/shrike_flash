// ------------------------------------------------------------
// main.v
// FPGAでLEDを一定周期で点滅させる最小構成のトップモジュール
// クロックをカウントして、一定回数ごとにLEDを反転させる
// ------------------------------------------------------------

// (* top *) は、このモジュールが設計の最上位であることを示す属性
(* top *) module blink(
  // FPGA外部から入力されるクロック信号(50MHz)
  (* iopad_external_pin, clkbuf_inhibit *) input clk,
  // LED出力ピン
  (* iopad_external_pin *) output LED,
  // LED用のイネーブル信号
  (* iopad_external_pin *) output LED_en,
  // クロック用のイネーブル信号
  (* iopad_external_pin *) output clk_en
  );

  // ----------------------------------------------------------
  // 内部レジスタ定義
  // ----------------------------------------------------------
  
  // クロックを数えるための32bitカウンタ
  // 実体は 1bitフリップフロップ × 32個
  reg [31:0] counter;
  // LEDのON/OFF状態を保持するレジスタ（1bit）
  reg LED_status;

  // LEDを常に有効にする（Vccに直結）
  assign LED_en = 1'b1;
  // クロックを常に有効にする（Vccに直結）
  assign clk_en = 1'b1;
  
  // ----------------------------------------------------------
  // クロック駆動の順序回路
  // ----------------------------------------------------------
  
  // クロックの立ち上がりごとに状態を更新する
  always @ (posedge clk) begin
    // 毎クロックごとにカウンタを +1
    counter <= counter + 1'b1;
    
    // カウンタが指定値に達したら
    if (counter == 25_000_000) begin
      // LEDの状態を反転する
      LED_status <= !LED_status;
      // カウンタを0に戻す
      counter <= 32'b0;
    end
  end

  // ----------------------------------------------------------
  // 出力配線
  // ----------------------------------------------------------
  
  // LED出力は内部状態をそのまま出す
  assign LED = LED_status;

endmodule 