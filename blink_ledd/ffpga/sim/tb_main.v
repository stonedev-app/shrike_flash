// ------------------------------------------------------------
// tb_main.v
// blink モジュールのテストベンチ
// ------------------------------------------------------------
`timescale 1ns / 1ps

module tb_main;

  // ----------------------------------------------------------
  // テストベンチ用信号
  // ----------------------------------------------------------
  reg clk;
  wire LED;
  wire LED_en;
  wire clk_en;

  // ----------------------------------------------------------
  // テスト対象モジュールのインスタンス化
  // ----------------------------------------------------------
  blink uut (
    .clk(clk),
    .LED(LED),
    .LED_en(LED_en),
    .clk_en(clk_en)
  );

  // ----------------------------------------------------------
  // クロック生成 (50MHz = 20ns周期)
  // ----------------------------------------------------------
  initial begin
    clk = 0;
  end

  always #10 clk = ~clk;  // 10ns毎にトグル → 20ns周期

  // ----------------------------------------------------------
  // 初期値設定とシミュレーション制御
  // ----------------------------------------------------------
  initial begin
    // VCDファイル出力設定（波形確認用）
    $dumpfile("tb_main.vcd");
    $dumpvars(0, tb_main);

    // テスト対象の内部レジスタを初期化
    // (実機ではリセット信号で行うべきだが、シミュレーション用)
    uut.counter = 32'd0;
    uut.LED_status = 1'b0;

    $display("=== Blink LED Simulation Start ===");
    $display("Time(ns) | counter    | LED");
    $display("---------+------------+----");

    // カウンタを閾値近くから開始してLEDトグルを早く確認
    #100;
    uut.counter = 32'd24_999_990;

    // 十分なクロックを待つ（LEDトグルを2回確認）
    #500;

    $display("=== Simulation End ===");
    $finish;
  end

  // ----------------------------------------------------------
  // モニタリング（状態変化を表示）
  // ----------------------------------------------------------
  always @(posedge clk) begin
    if (uut.counter >= 32'd24_999_990 || uut.counter <= 32'd10) begin
      $display("%8t | %10d | %b", $time, uut.counter, LED);
    end
  end

endmodule
