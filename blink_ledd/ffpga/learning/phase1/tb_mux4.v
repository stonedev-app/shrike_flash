// ------------------------------------------------------------
// tb_mux4.v
// 4入力マルチプレクサのテストベンチ
// ------------------------------------------------------------
`timescale 1ns / 1ps

module tb_mux4;

  // ----------------------------------------------------------
  // テストベンチ用信号
  // ----------------------------------------------------------
  reg [3:0] in;
  reg [1:0] sel;
  wire out;

  // ----------------------------------------------------------
  // テスト対象モジュールのインスタンス化
  // ----------------------------------------------------------
  mux4 uut (
    .in(in),
    .sel(sel),
    .out(out)
  );

endmodule
