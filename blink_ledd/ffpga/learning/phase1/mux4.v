// ------------------------------------------------------------
// mux4.v
// 4入力マルチプレクサ
// sel = 0b11 の場合 in[3] を出力
// sel = 0b10 の場合 in[2] を出力
// sel = 0b01 の場合 in[1] を出力
// sel = 0b00 の場合 in[0] を出力
// ------------------------------------------------------------

module mux4(
  input [3:0] in,
  input [1:0] sel,
  output out
);
  assign out = sel[1] ? (sel[0] ? in[3] : in[2]) : (sel[0] ? in[1] : in[0]);
endmodule